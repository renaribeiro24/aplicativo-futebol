import { spawnSync } from "node:child_process";
import { mkdirSync, renameSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

if (process.argv.length > 2)
  throw new Error(
    "Este comando aceita somente a instância Supabase local; argumentos remotos não são permitidos.",
  );
const root = fileURLToPath(new URL("../", import.meta.url));
const result = spawnSync(
  "supabase",
  ["gen", "types", "--local", "--schema", "public"],
  { cwd: root, encoding: "utf8", maxBuffer: 8 * 1024 * 1024 },
);
if (result.error) throw result.error;
if (result.status !== 0 || !result.stdout.includes("export type Database")) {
  process.stderr.write(
    result.stderr ||
      "Nenhum tipo Database válido foi gerado. Inicie o Supabase local e aplique as migrations locais primeiro.\n",
  );
  process.exitCode = 1;
} else {
  mkdirSync(new URL("../src/types/", import.meta.url), { recursive: true });
  const destination = new URL(
    "../src/types/database.types.ts",
    import.meta.url,
  );
  const temporary = new URL(
    "../src/types/database.types.ts.tmp",
    import.meta.url,
  );
  writeFileSync(
    temporary,
    "// Generated by Supabase CLI from the LOCAL public schema. Do not edit manually.\n" +
      result.stdout,
  );
  renameSync(temporary, destination);
  console.log(
    "Tipos reais do banco local gerados em src/types/database.types.ts",
  );
}
